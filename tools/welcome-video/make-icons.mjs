// Regenerates icons.js: the same lucide icons the resident app uses, as inline SVG strings.
// Run from the repo root: node tools/welcome-video/make-icons.mjs
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const req = createRequire(path.join(here, '../../apps/hoa/package.json'))
const React = req('react')
const { renderToStaticMarkup } = req('react-dom/server')
const L = req('lucide-react')

const names = [
  'Home', 'CreditCard', 'LayoutGrid', 'Sparkles', 'CircleUser', 'CircleHelp', 'MessageSquarePlus', 'FileText',
  'ClipboardList', 'ShieldAlert', 'CalendarDays', 'Megaphone', 'UsersRound', 'Vote', 'Send', 'Mail', 'MailCheck',
  'KeyRound', 'Share', 'EllipsisVertical', 'SquarePlus', 'Download', 'ChevronLeft', 'ChevronRight', 'Check', 'Landmark',
  'Copy', 'Lock', 'Wrench', 'Smartphone', 'Info',
]
const out = {}
for (const n of names) {
  if (!L[n]) throw new Error(`lucide-react has no ${n}`)
  out[n] = renderToStaticMarkup(React.createElement(L[n], { 'aria-hidden': true }))
}
writeFileSync(path.join(here, 'icons.js'), `// Generated by make-icons.mjs. Do not edit.\nwindow.ICONS = ${JSON.stringify(out, null, 1)}\n`)
console.log('icons:', names.length)
