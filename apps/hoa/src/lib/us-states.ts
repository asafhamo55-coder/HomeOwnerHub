/** Just the 2-letter codes (e.g. for Zod enum validation). */
export const US_STATE_CODES = US_STATES.map((s) => s.code) as readonly string[]

/** Set lookup for "is this a valid US state code?" */
const US_STATE_CODE_SET = new Set<string>(US_STATE_CODES)
export function isUsStateCode(value: unknown): value is string {
  return typeof value === 'string' && US_STATE_CODE_SET.has(value)
}
