/**
 * scripts/build-ga-statute-snapshot.ts
 *
 * Embeds the vetted Georgia statute snapshot
 *   scripts/fixtures/state-law/ga-ocga-44-3-art6-2026.txt
 * into packages/workflows/src/W30-state-law-brain/sources/georgia-snapshot.generated.ts
 * (the refresh job runs on Vercel, where reading a repo file at runtime is
 * not reliable), and rewrites data/statutes/ga.jsonl as the reviewable
 * artifact, the same way `ingest:state-law <STATE> --from-source` does for
 * FL/CA/TX.
 *
 * Usage (repo root), after editing the snapshot:
 *   pnpm exec tsx scripts/build-ga-statute-snapshot.ts
 *
 * No network, no database. The snapshot is parsed and validated first, so
 * a malformed edit fails here rather than in the weekly job. georgia.test.ts
 * fails if the generated module and the snapshot drift apart.
 */

import fs from 'node:fs'
import path from 'node:path'
import { parseGeorgiaSnapshot } from '../packages/workflows/src/W30-state-law-brain/sources/georgia'

const ROOT = path.resolve(__dirname, '..')
const SNAPSHOT = path.join(ROOT, 'scripts/fixtures/state-law/ga-ocga-44-3-art6-2026.txt')
const GENERATED = path.join(ROOT, 'packages/workflows/src/W30-state-law-brain/sources/georgia-snapshot.generated.ts')
const ARTIFACT = path.join(ROOT, 'data/statutes/ga.jsonl')

const text = fs.readFileSync(SNAPSHOT, 'utf8')
const snap = parseGeorgiaSnapshot(text)

fs.writeFileSync(
  GENERATED,
  [
    '// GENERATED by scripts/build-ga-statute-snapshot.ts from',
    '// scripts/fixtures/state-law/ga-ocga-44-3-art6-2026.txt. Do not edit by hand:',
    '// edit the snapshot and re-run the script. georgia.test.ts checks they match.',
    '',
    `export const GA_SNAPSHOT: string = ${JSON.stringify(text)}`,
    '',
  ].join('\n'),
  'utf8',
)

fs.writeFileSync(
  ARTIFACT,
  [
    `// ${snap.sourceName} - verbatim statute text, written by`,
    `// "pnpm exec tsx scripts/build-ga-statute-snapshot.ts" from the vetted snapshot`,
    `// scripts/fixtures/state-law/ga-ocga-44-3-art6-2026.txt (retrieved ${snap.retrieved}, valid until ${snap.validUntil}).`,
    '// Review artifact only: the refresh job reads the embedded snapshot, not this file. A citation can appear twice:',
    '// the text in force now and a later version with its effective_date (the adapter serves the one in force).',
    '// The legacy jsonl ingest refuses this file for that reason; use `pnpm ingest:state-law GA --from-source`.',
    '',
    ...snap.records.map((r) => JSON.stringify(r)),
    '',
  ].join('\n'),
  'utf8',
)

console.log(
  `[ga-snapshot] ${snap.records.length} records (retrieved ${snap.retrieved}, valid until ${snap.validUntil}) → ` +
    `${path.relative(ROOT, GENERATED)}, ${path.relative(ROOT, ARTIFACT)}`,
)
