// scripts/build-brand-assets.ts
/**
 * Builds every static HomeownerHub logo file (BL-098) from the one geometry
 * source, packages/ui/src/brand-geometry.ts, and the LOGO colours in
 * packages/ui/src/tokens.ts — so the files cannot drift from BrandLogo.tsx.
 *
 * Writes, identically, to apps/hoa/public/brand/ and
 * apps/marketing/public/brand/:
 *   logo-mark, logo-wordmark, logo-full   (+ -dark) as .svg and -512/-192 .png
 *   icon.svg          the scalable favicon (rounded tile)
 *   icon-touch.svg    full-bleed square source for the touch/maskable icons
 *   apple-touch-icon.png (180), icon-maskable-512.png, favicon.ico (16/32/48)
 * plus the Next.js file-convention copies: apps/hoa/src/app/favicon.ico and
 * apps/marketing/src/app/{favicon.ico,apple-icon.png,icon.svg}.
 *
 * The HOA /icon and /apple-icon routes draw the same geometry at request
 * time (apps/hoa/src/app/{icon,apple-icon}.tsx) and need no file here.
 *
 * Rasterised with sharp (a root devDependency). favicon.ico is assembled by
 * hand: an ICO file is a small directory header followed by PNG images, so
 * no extra dependency is needed.
 *
 * Run: pnpm brand:assets
 */

import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'
import { MARK, WORDMARK } from '../packages/ui/src/brand-geometry'
import { LOGO } from '../packages/ui/src/tokens'

type Mode = 'light' | 'dark'

const ROOT = process.cwd()
const BRAND_DIRS = ['apps/hoa/public/brand', 'apps/marketing/public/brand']
const SRC = 'Colours: LOGO in packages/ui/src/tokens.ts; geometry: packages/ui/src/brand-geometry.ts. Generated by scripts/build-brand-assets.ts.'

// ── SVG building blocks ───────────────────────────────────────────────────

function markBody({ rounded = true } = {}): string {
  const c = LOGO.light // the mark is identical in both modes
  const d = MARK.door
  return [
    `<rect width="32" height="32"${rounded ? ` rx="${MARK.tileRadius}"` : ''} fill="${c.tile}"/>`,
    `<g fill="none" stroke="${c.glyph}" stroke-linecap="round" stroke-linejoin="round">`,
    `  <path d="${MARK.stems.d}" stroke-width="${MARK.stems.strokeWidth}"/>`,
    `  <path d="${MARK.roof.d}" stroke-width="${MARK.roof.strokeWidth}"/>`,
    `</g>`,
    `<rect x="${d.x}" y="${d.y}" width="${d.width}" height="${d.height}" rx="${d.rx}" fill="${c.line}"/>`,
  ].join('\n  ')
}

function wordmarkBody(mode: Mode): string {
  const c = LOGO[mode]
  const glyphs = (hub: boolean) =>
    WORDMARK.glyphs
      .filter((g) => Boolean(g.hub) === hub)
      .map((g) => `    <path transform="translate(${g.x} 0)" d="${g.d}"/>`)
      .join('\n')
  return [
    `<g fill="none" stroke-width="${WORDMARK.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">`,
    `  <g stroke="${c.text}">`,
    glyphs(false),
    `  </g>`,
    `  <g stroke="${c.accent}">`,
    glyphs(true),
    `  </g>`,
    `</g>`,
  ].join('\n  ')
}

function svgDoc(w: number, h: number, comment: string, body: string, { label = true, px }: { label?: boolean; px?: number } = {}): string {
  const size = px ? `width="${px}" height="${px}"` : `width="${w}" height="${h}"`
  const a11y = label ? ' role="img" aria-label="HomeownerHub"' : ''
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" ${size}${a11y}>
  <!-- ${comment} ${SRC} -->
  ${body}
</svg>
`
}

// Lockup: the mark at 40px (scale 1.25), the wordmark scaled so its cap
// height sits centred on the mark — the same layout as the approved
// recommended-C-mark-plain-wordmark-lockup.svg.
const LOCKUP = { markScale: 1.25, wordX: 52, wordScale: 0.95, height: 40 }
const LOCKUP_WORD_Y = (LOCKUP.height - 20 * LOCKUP.wordScale) / 2 - 4.5 * LOCKUP.wordScale
const LOCKUP_WIDTH = Math.ceil(LOCKUP.wordX + (WORDMARK.width - 1.3) * LOCKUP.wordScale + 2)

function fullBody(mode: Mode): string {
  return [
    `<g transform="scale(${LOCKUP.markScale})">`,
    `  ${markBody()}`,
    `</g>`,
    `<g transform="translate(${LOCKUP.wordX} ${LOCKUP_WORD_Y.toFixed(2)}) scale(${LOCKUP.wordScale})">`,
    `  ${wordmarkBody(mode)}`,
    `</g>`,
  ].join('\n  ')
}

// Full-bleed square tile; the glyph at 0.8 scale, centred, so it stays
// inside the maskable-icon safe zone.
const touchBody = [
  `<rect width="32" height="32" fill="${LOGO.light.tile}"/>`,
  `<g transform="translate(3.2 3.2) scale(0.8)">`,
  `  ${markBody().split('\n  ').slice(1).join('\n    ')}`,
  `</g>`,
].join('\n  ')

// ── Files ─────────────────────────────────────────────────────────────────

const svgs: Record<string, string> = {
  'logo-mark.svg': svgDoc(32, 32, 'HomeownerHub mark (BL-098): an H whose crossbar is a roof, with a light-blue door.', markBody()),
  'logo-mark-dark.svg': svgDoc(
    32,
    32,
    'HomeownerHub mark (BL-098), dark-background variant: the same tile on purpose (it clears 3:1 on the dark canvas).',
    markBody(),
  ),
  'logo-wordmark.svg': svgDoc(
    WORDMARK.width,
    WORDMARK.height,
    'HomeownerHub wordmark (BL-098): monoline strokes, no font needed. "Hub" in the brand blue.',
    wordmarkBody('light'),
  ),
  'logo-wordmark-dark.svg': svgDoc(
    WORDMARK.width,
    WORDMARK.height,
    'HomeownerHub wordmark (BL-098), dark-background variant: light text, "Hub" in the dark primary.',
    wordmarkBody('dark'),
  ),
  'logo-full.svg': svgDoc(LOCKUP_WIDTH, LOCKUP.height, 'HomeownerHub full logo (BL-098): mark + wordmark, for light backgrounds.', fullBody('light')),
  'logo-full-dark.svg': svgDoc(LOCKUP_WIDTH, LOCKUP.height, 'HomeownerHub full logo (BL-098): mark + wordmark, for dark backgrounds.', fullBody('dark')),
  'icon.svg': svgDoc(32, 32, 'HomeownerHub mark (BL-098), scalable favicon.', markBody()),
  'icon-touch.svg': svgDoc(
    32,
    32,
    'Full-bleed square source for apple-touch-icon / maskable PWA icons: the OS applies its own corner mask, so no radius and a wider safe margin.',
    touchBody,
    { label: false, px: 180 },
  ),
}

async function png(svg: string, width: number, { opaque = false } = {}): Promise<Buffer> {
  const vbWidth = Number(/viewBox="0 0 ([\d.]+)/.exec(svg)![1])
  // Rasterise at (at least) the target resolution, then resize exactly.
  const density = Math.max(72, Math.ceil((72 * width) / vbWidth) * 2)
  let img = sharp(Buffer.from(svg), { density }).resize({ width })
  if (opaque) img = img.flatten({ background: LOGO.light.tile })
  return img.png({ compressionLevel: 9 }).toBuffer()
}

/** ICO = 6-byte header + 16-byte directory entry per image + PNG payloads. */
function ico(images: { size: number; data: Buffer }[]): Buffer {
  const header = Buffer.alloc(6)
  header.writeUInt16LE(0, 0) // reserved
  header.writeUInt16LE(1, 2) // type: icon
  header.writeUInt16LE(images.length, 4)
  let offset = 6 + 16 * images.length
  const entries = images.map(({ size, data }) => {
    const e = Buffer.alloc(16)
    e.writeUInt8(size >= 256 ? 0 : size, 0)
    e.writeUInt8(size >= 256 ? 0 : size, 1)
    e.writeUInt8(0, 2) // palette colours
    e.writeUInt8(0, 3) // reserved
    e.writeUInt16LE(1, 4) // colour planes
    e.writeUInt16LE(32, 6) // bits per pixel
    e.writeUInt32LE(data.length, 8)
    e.writeUInt32LE(offset, 12)
    offset += data.length
    return e
  })
  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)])
}

async function main(): Promise<void> {
  const out: Record<string, Buffer | string> = { ...svgs }
  for (const name of ['logo-mark', 'logo-mark-dark', 'logo-wordmark', 'logo-wordmark-dark', 'logo-full', 'logo-full-dark']) {
    for (const w of [512, 192]) out[`${name}-${w}.png`] = await png(svgs[`${name}.svg`]!, w)
  }
  out['apple-touch-icon.png'] = await png(svgs['icon-touch.svg']!, 180, { opaque: true })
  out['icon-maskable-512.png'] = await png(svgs['icon-touch.svg']!, 512, { opaque: true })
  out['favicon.ico'] = ico(
    await Promise.all([16, 32, 48].map(async (size) => ({ size, data: await png(svgs['icon.svg']!, size) }))),
  )

  for (const dir of BRAND_DIRS) {
    await mkdir(path.join(ROOT, dir), { recursive: true })
    for (const [name, data] of Object.entries(out)) await writeFile(path.join(ROOT, dir, name), data)
    console.log(`  ${Object.keys(out).length} files → ${dir}/`)
  }

  // Next.js file-convention icons.
  const conventions: [string, Buffer | string][] = [
    ['apps/hoa/src/app/favicon.ico', out['favicon.ico']!],
    ['apps/marketing/src/app/favicon.ico', out['favicon.ico']!],
    ['apps/marketing/src/app/apple-icon.png', out['apple-touch-icon.png']!],
    ['apps/marketing/src/app/icon.svg', out['icon.svg']!],
  ]
  for (const [file, data] of conventions) {
    await writeFile(path.join(ROOT, file), data)
    console.log(`  ${file}`)
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
