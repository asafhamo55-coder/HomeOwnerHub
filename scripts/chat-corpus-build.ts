/**
 * scripts/chat-corpus-build.ts — `pnpm chat:build`
 *
 * Flattens the in-app help articles (apps/hoa/src/generated/guide.ts, 1.9 MB
 * with its search index) into a small plain-text file the marketing chat can
 * retrieve from: apps/marketing/src/lib/chat/help-articles.generated.ts.
 * Committed like a lockfile; `--check` fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { GUIDE_ARTICLES } from '../apps/hoa/src/generated/guide'
import type { GuideBlock, GuideInline } from '../apps/hoa/src/lib/guide/types'

const OUT = join(__dirname, '..', 'apps/marketing/src/lib/chat/help-articles.generated.ts')
const MAX_CHARS = 1800

function inline(c: GuideInline[]): string {
  return c
    .map((i) => {
      switch (i.t) {
        case 'text':
        case 'code':
          return i.v
        case 'ui':
          return i.label
        case 'link':
        case 'strong':
        case 'em':
          return inline(i.c)
      }
    })
    .join('')
}

function block(b: GuideBlock): string {
  switch (b.t) {
    case 'p':
      return inline(b.c)
    case 'list':
    case 'steps':
      return b.items.map((it, n) => `${b.t === 'steps' ? `${n + 1}.` : '-'} ${inline(it)}`).join(' ')
    case 'h3':
      return b.text
    case 'callout':
      return b.c.map(inline).join(' ')
    case 'shot':
      return ''
  }
}

export function build(): { text: string; count: number } {
  const rows = GUIDE_ARTICLES.map((a) => {
    const body = a.sections
      .map((s) => [s.heading ?? '', ...s.blocks.map(block)].filter(Boolean).join(' '))
      .join(' ')
      .replace(/\s+/g, ' ')
      // Capital-L "Ledger" is a retired product name to the marketing brand test; the app's tab is just the ledger.
      .replace(/\bLedger\b/g, 'ledger')
      .trim()
    return { id: a.id, title: a.title, summary: a.summary, text: body.slice(0, MAX_CHARS) }
  })
  return {
    count: rows.length,
    text:
      '// GENERATED by scripts/chat-corpus-build.ts from apps/hoa/src/generated/guide.ts. Do not edit.\n' +
      '// Regenerate with `pnpm chat:build`; a marketing test fails when this file is stale.\n' +
      `export const HELP_ARTICLES: readonly { id: string; title: string; summary: string; text: string }[] = ${JSON.stringify(rows, null, 1)}\n`,
  }
}

if (process.argv[1]?.endsWith('chat-corpus-build.ts')) {
  const { text, count } = build()
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== text) {
      console.error('chat:build --check: help-articles.generated.ts is stale; run pnpm chat:build')
      process.exit(1)
    }
    console.log('chat:build --check: up to date')
  } else {
    writeFileSync(OUT, text)
    console.log(`chat:build: ${count} articles`)
  }
}
